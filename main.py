# Вводим число или слово
text = input("Введите число или слово: ")

# Проверяем, чтобы длина ввода была не больше 20 символов
if len(text) > 20:
    print("Ошибка! Слишком большое число или длинное слово.")

# Если введены только цифры
elif text.isdigit():

    # Переменная для подсчёта цифр
    count = 0

    # Цикл for проходит по каждой цифре
    for i in text:
        count += 1

    # Выводим количество цифр
    print("Количество цифр:", count)

# Если введены только буквы
elif text.isalpha():

    # Переменная для перевёрнутого слова
    result = ""

    # Начинаем с последней буквы слова
    i = len(text) - 1

    # Цикл while идёт от последней буквы к первой
    while i >= 0:
        result += text[i]
        i -= 1

    # Выводим перевёрнутое слово
    print("Перевернутое слово:", result)

# Если введены буквы и цифры вместе или другие символы
else:
    print("Ошибка! Введите только число или только буквы.")
